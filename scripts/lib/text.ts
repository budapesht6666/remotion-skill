/**
 * Текстовые мелочи, общие для озвучки и нарезки.
 */

/**
 * Убирает комбинируемый акут U+0301 — знак ударения, которым в `script.ts`
 * правится произношение («замо́к», «пче́ла»).
 *
 * Знак нужен только TTS-движку: ElevenLabs по нему реально переставляет
 * ударение (проверено на multilingual_v2). Но дальше по конвейеру он мусор —
 * в караоке-субтитре «замо́к» показывается с висящей чёрточкой, а в
 * посимвольном alignment акут занимает отдельный слот и приклеивается к слову.
 * Поэтому синтезируем с ним, а сохраняем и рисуем — без него.
 */
export function stripStress(text: string): string {
  return text.replace(/́/g, "");
}

/**
 * Корни, по которым слово считается матерным. «еб» и «ху» пишутся с коротким
 * префиксом приставки, иначе под маску попадают «требуй» и подобные.
 */
const PROFANITY = [
  /^(?:[внзапдоуксб]{0,4})?[еёэ]б[аеёиуыя]/i,
  /^(?:[нипоазв]{0,3})?х[уy][йёеиюя]/i,
  /пизд/i,
  /бл[яа]д/i,
  /^бля(?:ть)?$/i,
  /^(?:за|на|от|под|в|с)?еб[уаио]/i,
];

/**
 * Прячет мат в тексте субтитра: первая буква остаётся, остальные становятся
 * звёздочками («блядь» → «б****»). В звуке реплика не трогается — интонация
 * держит сцену, а площадкам достаётся уже вычищенный текст на экране.
 *
 * Слова разбираются по буквенным токенам, поэтому составные вроде
 * «ёбушки-воробушки» маскируются частями: цензурится только матерный корень.
 */
export function maskProfanity(text: string): string {
  return text.replace(/[А-Яа-яЁёA-Za-z]+/g, (token) => {
    if (!PROFANITY.some((re) => re.test(token))) return token;
    return token[0] + "*".repeat(token.length - 1);
  });
}
