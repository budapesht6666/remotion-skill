/**
 * Детерминированный ГПСЧ для сцен, где нужна воспроизводимость «случайности»
 * (начальные условия физической симуляции, разлёт частиц/искр).
 *
 * Один seed → одинаковая последовательность каждый раз, поэтому одиночный кадр
 * (still) и полный рендер всегда совпадают. Никогда не используем Math.random()
 * в композициях и bake-скриптах.
 *
 * Копия проверенного mulberry32 из MatrixRain/atlas.ts, вынесенная для
 * переиспользования (bake физики, будущие слои эффектов).
 */

/** mulberry32: быстрый детерминированный ГПСЧ, возвращает число в [0, 1). */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Случайное число в диапазоне [min, max) из переданного генератора. */
export function range(rng: () => number, min: number, max: number): number {
  return min + rng() * (max - min);
}
