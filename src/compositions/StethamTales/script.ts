/**
 * СЦЕНАРИЙ «СТЕТХЕМ ПОЯСНЯЕТ МОНСТРАМ ЗА ПАСЕКУ».
 *
 * Отличие от `BeekeeperKong` — способ сборки. Там каждый бит был репликой
 * персонажа, и длина кадра равнялась длине реплики (плюс хвост), из-за чего на
 * каждой склейке возникала микропауза. Здесь ролик держит **сплошной закадровый
 * монолог**: фразы синтезируются по отдельности (так ElevenLabs держит
 * интонацию), но склеиваются встык по таймингам слов — тишина по краям каждого
 * файла срезается. Голос не останавливается ни разу до самого конца.
 *
 * Видеоряд поэтому живёт своей жизнью: планы привязаны не ко времени, а к фразе
 * (`line`) и делят её длительность по весам (`weight`). На фразе про двух
 * монстров три плана по секунде — получаются те самые «быстрые вспышки», хотя
 * голос в этот момент читает одно предложение. Если озвучка перегенерится и
 * станет длиннее, монтаж поедет вместе с ней сам.
 *
 * Порядок сборки:
 *   npm run vo    -- StethamTales     # 26 фраз, голос stetham
 *   npm run broll -- StethamTales     # склейка озвучки + нарезка планов
 *
 * Кадры найдены по контактным листам (out/<фильм>/sheets/), каждый проверен
 * глазами. Правило прошлого ролика сохранено: Стетхем и титаны никогда не в
 * одном кадре — их связывает только монтажный стык.
 */

