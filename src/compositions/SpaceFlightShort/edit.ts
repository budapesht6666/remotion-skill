export type ClipId =
  | "ice"
  | "ion"
  | "hive"
  | "warden-kill"
  | "leviathan"
  | "leviathan-kill"
  | "title";

export type Piece = {
  /** Имя куска: на него ссылаются надписи композиции. */
  id: string;
  clip: ClipId;
  /** Длина куска в кадрах ролика. */
  frames: number;
  /**
   * Якорь времени: кадр исходника `src` встаёт на кадр `at` куска. От него
   * время раскладывается в обе стороны — так смерть босса попадает ровно на
   * сильную долю, как бы ни менялась скорость вокруг.
   */
  anchor: { src: number; at: number };
  /**
   * Speed-ramp: ключи [кадр исходника, скорость], между ключами скорость
   * меняется плавно (smoothstep), за крайними держится. Только ≥ 1: материал
   * снят на 60 к/с, и замедление ниже реального времени дублировало бы кадры —
   * своё slow-mo у игры уже есть, оно в самом материале.
   */
  speed?: [number, number][];
  /**
   * Куда целить панч-зум на убийствах в этом куске (доли кадра). Камера игры
   * 2.5D, мировые x/z из лога в экран линейно не ложатся — точка снята по кадру.
   */
  focus?: [number, number];
};

