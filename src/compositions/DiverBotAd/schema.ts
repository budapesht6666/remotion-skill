import { z } from "zod";

/**
 * Схема пропсов рекламного ролика — она включает редактор в правой панели
 * студии, и громкости с музыкой можно крутить, не трогая код.
 *
 * Что глушит панель целиком, без ошибки и предупреждения (проверено на
 * `Whiteboard`): приведения `as` в `defaultProps`, ссылки на константы и любая
 * арифметика там же, спреды объектов. Поэтому в `defaultProps` только литералы,
 * а пути к файлам — пустой строкой, не `null`.
 *
 * Поля из `ad.json` описаны слабо (`z.array(z.any())`): править их руками
 * нечего, следующий `npm run ad` всё равно перезапишет, а подробная схема на
 * четырнадцать фраз с пословными таймингами замусорила бы панель.
 */
export const diverBotAdSchema = z.object({
  /** Путь к манифесту внутри public/, например «vo/DiverBotAd/ad.json». */
  adFile: z.string(),

  // ─── звук ────────────────────────────────────────────────────────────
  /** Музыка тёмной половины. Пустая строка → без музыки. */
  musicDark: z.string(),
  /** Музыка светлой половины: ломается ровно на вспышке. */
  musicLight: z.string(),
  musicDarkVolume: z.number().min(0).max(1),
  musicLightVolume: z.number().min(0).max(1),
  /** Звук уведомления на стыке — ради него ролик и существует. */
  alertVolume: z.number().min(0).max(1),
  /** Бас-удар под вспышку. */
  dropVolume: z.number().min(0).max(1),
  /** Ход секундной стрелки в первом бите. */
  tickVolume: z.number().min(0).max(1),

  // ─── субтитры ────────────────────────────────────────────────────────
  /** В лентах звук выключен по умолчанию: без субтитров ролик немой. */
  showCaptions: z.boolean(),

  // ─── из ad.json, руками не трогать ───────────────────────────────────
  narrationFile: z.string(),
  phrases: z.array(z.any()),
  shots: z.array(z.any()),
});

export type DiverBotAdSchema = z.infer<typeof diverBotAdSchema>;
