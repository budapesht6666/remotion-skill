/**
 * Какую сцену рисует композиция. Разделение по типу, а не по файлу: у половины
 * планов вообще нет видеофайла (их рисует React), а у остальных источники
 * разной природы — промо-видео сайта, захват браузера, клип из Gemini.
 */
export type SceneKind =
  /** Тёмный кадр-подложка: клип из Gemini, а пока его нет — нативный фон. */
  | "dark"
  /** Промо-видео сайта: чёрная робо-рука на белом (hero.mp4). */
  | "hero"
  /** Захват закреплённой секции промо-сайта с анимацией цены и RSI. */
  | "chart"
  /** Захват мини-аппки в рамке телефона. */
  | "app"
  /** Вспышка тьма→свет. */
  | "flash"
  /** Перегруз: сетка панелей набирается и уходит вглубь. Рисует React. */
  | "wall"
  /** Девять событий продукта его же значками. Рисует React. */
  | "events"
  /** Пузырь телеграм-алерта, рисуется React. */
  | "telegram"
  /** Карточка подписки, рисуется React. */
  | "offer"
  /** Финальная плашка: логотип, кнопка, хендл, дисклеймер. */
  | "end";

/** План: что показываем под фразой. Планы одной фразы делят её длительность. */
export type Shot = {
  /** id фразы из SCRIPT, под которую идёт план. */
  line: string;
  scene: SceneKind;
  /**
   * Сколько фраз подряд занимает план, считая свою. По умолчанию 1.
   * Нужен там, где картинка обязана идти НЕПРЕРЫВНО, а текст за это время
   * успевает смениться: анимация графика рисуется одним движением под три
   * фразы, и рвать её на три куска значило бы трижды дёрнуть линию RSI.
   */
  span?: number;
  /** Доля длительности фразы. Планы одной фразы делят её пропорционально. */
  weight?: number;
  /** Зачем план в истории — для читаемости сценария. */
  note?: string;

  /**
   * Путь внутри public/ для сцен с видео. Для `dark` может отсутствовать на
   * диске: сцена тогда деградирует до нативного фона, и ролик всё равно
   * собирается — иначе работа встала бы до прихода клипов из Gemini.
   */
  media?: string;
  /** С какой секунды исходника берём кусок. */
  from?: number;
  /**
   * Ретайминг источника: 0.5 — вдвое медленнее исходника.
   * `"fit"` растягивает исходник ровно на длину плана — так захват анимации
   * сайта подчиняется диктору, а не наоборот: переозвучили фразу, и рисунок
   * сам подстроился под новую длину.
   */
  speed?: number | "fit";

  /** Кадрирование: увеличение и сдвиг центра, −1…1. */
  zoom?: number;
  panX?: number;
  panY?: number;

  /** Короткая надпись поверх кадра. Не дублирует субтитр, а добавляет факт. */
  overlay?: string;
};

